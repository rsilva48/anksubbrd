import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const testDirectory = mkdtempSync(join(tmpdir(), 'anksubbrd-version-test-'));
const script = resolve(fileURLToPath(new URL('./post-commit-version.mjs', import.meta.url)));
const git = (...args) => execFileSync('git', args, { cwd: testDirectory, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
git('init');
git('config', 'user.email', 'version-test@example.invalid');
git('config', 'user.name', 'Version test');
git('config', 'commit.gpgsign', 'false');
git('config', 'tag.gpgsign', 'false');
writeFileSync(join(testDirectory, 'example.txt'), 'one\n');
git('add', 'example.txt');
git('commit', '-m', 'test: first');
execFileSync(process.execPath, [script], { cwd: testDirectory });
assert.equal(git('describe', '--tags', '--exact-match', 'HEAD'), 'v0.1.1');
execFileSync(process.execPath, [script], { cwd: testDirectory });
assert.equal(git('tag', '--list').split(/\r?\n/).length, 1);
writeFileSync(join(testDirectory, 'example.txt'), 'two\n');
git('add', 'example.txt');
git('commit', '-m', 'test: second');
execFileSync(process.execPath, [script], { cwd: testDirectory });
assert.equal(git('describe', '--tags', '--exact-match', 'HEAD'), 'v0.1.2');
assert.equal(git('cat-file', '-t', 'v0.1.2'), 'tag');
console.log('Versioning verified: annotated tags v0.1.1 and v0.1.2; rerun is idempotent.');
